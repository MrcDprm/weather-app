const WEST = 25.5;
const NORTH = 42.4;
// Türkiye'nin enleminde (39°) bir boylam derecesi, bir enlem derecesinin bu kadarıdır; harita basık görünmesin diye
const LON_SCALE = Math.cos((39 * Math.PI) / 180);
const PIXELS_PER_DEGREE = MAP_WIDTH / ((45 - WEST) * LON_SCALE);

/** Koordinat → harita üzerindeki konum, yüzde olarak (ekran boyutundan bağımsız). */
export function mapPosition(lat, lon) {
  return {
    x: (((lon - WEST) * LON_SCALE * PIXELS_PER_DEGREE) / MAP_WIDTH) * 100,
    y: (((NORTH - lat) * PIXELS_PER_DEGREE) / MAP_HEIGHT) * 100,
  };
}

